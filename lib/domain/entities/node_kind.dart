/// 노드의 종류.
///
/// 파일·디렉토리는 관리 폴더 안에 **실체가 있는** 노드이고, 키워드는 디스크에 남지
/// 않고 DB 안에만 있는 노드다. 종류를 불리언(폴더인가)이 아니라 열거로 두는 이유는,
/// "폴더가 아니다"가 곧 "디스크에 있는 파일이다"를 뜻하던 자리들이 키워드를 조용히
/// 파일로 오인하지 않게 하기 위함이다 — 그런 자리는 [NodeKind.file]을 직접 묻는다.
///
/// 저장은 이름 기반이라 열거 순서를 바꿔도 기존 DB에 영향이 없다.
enum NodeKind {
  /// 디스크에 있는 일반 파일.
  file,

  /// 디스크에 있는 디렉토리.
  directory,

  /// 디스크에 남지 않고 DB에만 있는 노드. **이름 하나가 전부**이며, 부연 정보는
  /// 본문이 아니라 태그로 붙인다 — 그래야 필터·정렬·그룹에 그대로 걸린다. 작가·
  /// 시리즈처럼 그 자체가 속성을 갖는 대상을 세워 링크 태그로 가리키는 자리다.
  keyword,
}
